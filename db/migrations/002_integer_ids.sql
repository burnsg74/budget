CREATE TABLE accounts_new (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_id uuid UNIQUE,
  name text NOT NULL CHECK (char_length(btrim(name)) > 0),
  match_text text NOT NULL DEFAULT '',
  type text NOT NULL CHECK (
    type IN (
      'checking',
      'income',
      'credit_card',
      'loan',
      'bill',
      'household',
      'other'
    )
  ),
  institution text,
  mask text,
  opening_balance_cents bigint NOT NULL DEFAULT 0,
  opening_on date,
  expected_amount_cents bigint,
  due_day smallint CHECK (due_day IS NULL OR due_day BETWEEN 1 AND 31),
  schedule_active boolean NOT NULL DEFAULT false,
  archived boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO accounts_new (
  id,
  legacy_id,
  name,
  match_text,
  type,
  institution,
  mask,
  opening_balance_cents,
  opening_on,
  expected_amount_cents,
  due_day,
  schedule_active,
  archived,
  created_at
)
SELECT
  row_number() OVER (ORDER BY created_at, id)::int,
  id,
  name,
  name,
  type,
  institution,
  mask,
  opening_balance_cents,
  opening_on,
  expected_amount_cents,
  due_day,
  schedule_active,
  archived,
  created_at
FROM accounts;

CREATE TABLE transactions_new (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id integer NOT NULL REFERENCES accounts_new (id) ON DELETE RESTRICT,
  matched_account_id integer REFERENCES accounts_new (id) ON DELETE RESTRICT,
  posted_on date NOT NULL,
  description text NOT NULL,
  amount_cents bigint NOT NULL,
  check_number text,
  status text NOT NULL,
  classification text,
  fingerprint text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (matched_account_id IS NULL OR matched_account_id <> account_id)
);

INSERT INTO transactions_new (
  id,
  account_id,
  matched_account_id,
  posted_on,
  description,
  amount_cents,
  check_number,
  status,
  classification,
  fingerprint,
  created_at
)
SELECT
  row_number() OVER (ORDER BY t.created_at, t.id)::int,
  source.id,
  matched.id,
  t.posted_on,
  t.description,
  t.amount_cents,
  t.check_number,
  t.status,
  t.classification,
  t.fingerprint,
  t.created_at
FROM transactions t
JOIN accounts_new source ON source.legacy_id = t.account_id
LEFT JOIN accounts_new matched ON matched.legacy_id = t.matched_account_id;

CREATE TABLE import_batches_new (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id integer NOT NULL REFERENCES accounts_new (id) ON DELETE RESTRICT,
  file_name text NOT NULL,
  skipped_status_count integer NOT NULL,
  duplicate_count integer NOT NULL,
  inserted_count integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO import_batches_new (
  id,
  account_id,
  file_name,
  skipped_status_count,
  duplicate_count,
  inserted_count,
  created_at
)
SELECT
  row_number() OVER (ORDER BY b.created_at, b.id)::int,
  source.id,
  b.file_name,
  b.skipped_status_count,
  b.duplicate_count,
  b.inserted_count,
  b.created_at
FROM import_batches b
JOIN accounts_new source ON source.legacy_id = b.account_id;

